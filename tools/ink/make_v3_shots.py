"""Build v3 shot lists (Zen 2026-11-16: v2 camera plan rejected as dizzy; picked option A = merge the short cards).

v3 = v1 exactly (same voice, same v1 camera = one slow push-in per shot), except runs of very short shots are
merged into one longer shot. Merged shot spans first.f0 -> last.f1; the voice-synced 'at' frames inside it stay
absolute, so every word still lands where v1 had it. Only the layout of the merged shot is rewritten here.
Shots shorter than MIN_S that are NOT merged are listed on run so nothing slips by unseen.

usage: python tools/ink/make_v3_shots.py   (writes engine/ink/parts/shots_v3/p01.json, p02.json)
"""
import copy
import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SRC = REPO / 'engine/ink/parts/shots'
DST = REPO / 'engine/ink/parts/shots_v3'
FPS = 30
MIN_S = 2.0  # report threshold: shots under this stay visible in the run log

# first f0 of a run -> {'span': [f0s merged], 'bg': ..., 'els': [...], optional chip keys}
MERGES = {
    # "not a model, not a ticket": two 1.0 s cards -> one card, model left, ticket right
    143: {'span': [143, 174], 'bg': {'card': True}, 'els': [
        {'t': 'tower', 'x': 560, 'y': 820, 'h': 460},
        {'t': 'words', 'text': 'A MODEL', 'x': 560, 'y': 920, 'size': 70, 'at': 151},
        {'t': 'cross', 'x': 560, 'y': 600, 'size': 460, 'at': 151},
        {'t': 'ticket', 'x': 1360, 'y': 520, 'w': 560, 'text': 'TOUR EIFFEL · 1 FR', 'at': 176},
        {'t': 'words', 'text': 'A TICKET', 'x': 1360, 'y': 920, 'size': 70, 'at': 180},
        {'t': 'cross', 'x': 1360, 'y': 520, 'size': 460, 'at': 182},
    ]},
    # tower low-angle plate (no elements) + 1.6 s "1889" card -> 1889 written on the plate
    1001: {'span': [1001, 1079], 'keep_bg': 1001, 'els': [
        {'t': 'words', 'text': '1889', 'x': 1380, 'y': 460, 'size': 220, 'color': 'orange', 'at': 1102},
        {'t': 'underline', 'x': 1380, 'y': 580, 'w': 440, 'at': 1110},
    ]},
    # "taken apart" card + 1.3 s "HATED" plate -> one card: tower comes apart, grumpy Parisians, HATED stamp
    1263: {'span': [1263, 1335], 'bg': {'card': True}, 'els': [
        {'t': 'tower', 'x': 760, 'y': 1000, 'h': 700, 'cut': [1284, 1294]},
        {'t': 'words', 'text': 'TAKEN APART', 'x': 760, 'y': 150, 'size': 90, 'color': 'orange', 'at': 1284},
        {'t': 'sprite', 'src': 'ink60/cast/parisian_1.png', 'x': 1380, 'y': 1000, 'h': 460, 'at': 1337},
        {'t': 'sprite', 'src': 'ink60/cast/parisian_3.png', 'x': 1660, 'y': 1000, 'h': 460, 'flip': True, 'at': 1344},
        {'t': 'stamp', 'text': 'HATED', 'x': 1520, 'y': 380, 'rot': -8, 'color': 'red', 'at': 1362},
    ]},
}


def build(part):
    d = json.loads((SRC / f'{part}.json').read_text(encoding='utf-8'))
    out = copy.deepcopy(d)
    out['_doc'] = f'v3 of {part} (generated by tools/ink/make_v3_shots.py; edit there). ' + d.get('_doc', '')
    by_f0 = {s['f0']: s for s in d['shots']}
    shots, skip = [], set()
    for s in d['shots']:
        if s['f0'] in skip:
            continue
        m = MERGES.get(s['f0'])
        if not m:
            shots.append(copy.deepcopy(s))
            continue
        run = [by_f0[f] for f in m['span']]
        for a, b in zip(run, run[1:]):
            assert a['f1'] == b['f0'], f'{part}: merge run at {s["f0"]} is not contiguous'
        skip |= {r['f0'] for r in run[1:]}
        merged = copy.deepcopy(by_f0[m['keep_bg']]) if 'keep_bg' in m else {'bg': m['bg']}
        merged.update(f0=run[0]['f0'], f1=run[-1]['f1'])
        merged['els'] = m['els']
        shots.append(merged)
    for a, b in zip(shots, shots[1:]):
        assert a['f1'] == b['f0'], f'{part}: gap/overlap at {a["f1"]}->{b["f0"]}'
    assert shots[0]['f0'] == d['f0'] and shots[-1]['f1'] == d['f1'], f'{part}: span changed'
    out['shots'] = shots
    DST.mkdir(parents=True, exist_ok=True)
    (DST / f'{part}.json').write_text(json.dumps(out, indent=1, ensure_ascii=False), encoding='utf-8')
    short = [(s['f0'], round((s['f1'] - s['f0']) / FPS, 2)) for s in shots if s['f1'] - s['f0'] < MIN_S * FPS]
    print(part, len(d['shots']), '->', len(shots), 'shots; still under', MIN_S, 's:', short)


if __name__ == '__main__':
    for p in ('p01', 'p02'):
        build(p)
