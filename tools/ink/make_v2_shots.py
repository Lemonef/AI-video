"""Build v2 shot lists (Zen 2026-11-16: "show me the new one as the new version too").

v1 shot JSONs stay untouched. v2 = same parts, same timings, same voice, plus:
  - a per-shot virtual camera (`cam`: [scale, focusX, focusY] from -> to) so framing varies
    (wide / medium / close, pans, tilts, pull-outs) instead of one push-in on every shot;
  - bare paper cards that carry a character turned into existing plates (no new paid art).
Plate shots that get a cam have their own plate zoom flattened to [1, 1] so the two moves never stack.

usage: python tools/ink/make_v2_shots.py   (writes engine/ink/parts/shots_v2/p01.json, p02.json)
"""
import copy
import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SRC = REPO / 'engine/ink/parts/shots'
DST = REPO / 'engine/ink/parts/shots_v2'
CX, CY = 960, 540  # stage centre (1920x1080)

# shot f0 -> cam (from, to[, span])
CAMS = {
    0:    ([1.12, 900, 500], [1.0, CX, CY]),               # open tight on the words, pull out to Paris
    55:   ([1.3, 560, 700], [1.0, CX, CY]),                # close on Lustig, pull out wide so the whole SOLD stamp lands in frame
    143:  ([1.0, CX, 700], [1.08, CX, 700]),
    174:  ([1.0, CX, 520], [1.06, CX, 520]),
    275:  ([1.5, 560, 450], [1.0, CX, CY], 0.6),           # close on the cash, pull out to the room
    335:  ([1.2, 600, 470], [1.2, 900, 470]),              # tracking with the walk; words at y200 stay in frame
    402:  ([1.3, 1300, 600], [1.15, 700, 500]),            # Capone first, pan to the mugshot
    455:  ([1.2, 1000, 700], [1.0, CX, CY]),               # rope low, ease out; ESCAPED (x600) stays in frame
    666:  ([1.0, CX, CY], [1.1, CX, CY]),
    788:  ([1.0, CX, CY], [1.25, 1100, 600]),
    889:  ([1.2, 700, 520], [1.2, 1220, 520]),             # lateral pan along the crowd; ticks at y330 in frame
    1079: ([1.2, CX, CY], [1.0, CX, CY]),                  # birdseye pull-out
    1128: ([1.15, 1300, CY], [1.15, 620, CY]),             # pan right -> left
    1198: ([1.2, 760, 540], [1.2, 1160, 540]),             # pan along the timeline
    1263: ([1.1, CX, 640], [1.0, CX, CY]),
    1335: ([1.0, CX, CY], [1.15, CX, 500]),                # quick punch-in
    1375: ([1.4, 680, 600], [1.15, 1300, 560]),            # artist -> caricature
    1455: ([1.1, CX, 400], [1.1, CX, 700]),                # quote first, tilt down to the chimney
    1555: ([1.3, 620, 650], [1.05, 1000, 540]),
}
# card -> existing plate (f0 -> plate); 'drop' lists element types the plate replaces
TO_PLATE = {
    275:  {'plate': 'ink60full/plates/hotel_suite_corner_34.png'},
    788:  {'plate': 'ink60full/plates/forger_desk_night.png', 'drop': ['redact']},  # redaction bars read as black slabs on a plate
    1079: {'plate': 'ink60full/plates/paris_birdseye_champ_de_mars.png', 'drop': ['tower']},
}


def build(part):
    d = json.loads((SRC / f'{part}.json').read_text(encoding='utf-8'))
    out = copy.deepcopy(d)
    out['_doc'] = f'v2 of {part} (generated by tools/ink/make_v2_shots.py; edit there). ' + d.get('_doc', '')
    for s in out['shots']:
        f0 = s['f0']
        if f0 in TO_PLATE:
            conv = TO_PLATE[f0]
            s['bg'] = {'plate': conv['plate'], 'zoom': [1.0, 1.0]}
            s['els'] = [e for e in s['els'] if e['t'] not in conv.get('drop', [])]
        if f0 in CAMS:
            c = CAMS[f0]
            s['cam'] = {'from': c[0], 'to': c[1], **({'span': c[2]} if len(c) > 2 else {})}
            if 'plate' in s['bg']:
                s['bg']['zoom'] = [1.0, 1.0]
    DST.mkdir(parents=True, exist_ok=True)
    (DST / f'{part}.json').write_text(json.dumps(out, indent=1, ensure_ascii=False), encoding='utf-8')
    used = sum(1 for s in out['shots'] if 'cam' in s)
    print(part, len(out['shots']), 'shots,', used, 'with cam')


if __name__ == '__main__':
    missing = set(CAMS) | set(TO_PLATE)
    for p in ('p01', 'p02'):
        build(p)
        missing -= {s['f0'] for s in json.loads((SRC / f'{p}.json').read_text(encoding='utf-8'))['shots']}
    assert not missing, f'cam/plate keys match no shot f0: {sorted(missing)}'
